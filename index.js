// 💬 Text messages
bot.on('message', async (msg) => {
  if (!msg.text) return
  const text = msg.text

  if (text.startsWith('/image')) {
    await bot.sendMessage(msg.chat.id, '📝 Prompt එකක් දෙන්න! විදිය: /image a futuristic car in sri lanka')
    return
  }
  if (text.startsWith('/') || text.startsWith('.')) return
  await handleChat(msg)
})

